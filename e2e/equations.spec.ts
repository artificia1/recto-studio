import { test, expect } from '@playwright/test';
import { importProject, menuCommand, savedProject } from './fixtures';
import { readFile, mkdir, copyFile } from 'node:fs/promises';

test('equations preview, export, undo and remain editable after reopening', async ({ page }) => {
  test.setTimeout(180000);
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.route(/fonts\.(googleapis|gstatic)\.com/, route => route.abort());
  await page.goto('/');
  await importProject(page);
  await menuCommand(page, 'Insert an editable LaTeX equation');
  const modal = page.getByRole('dialog', { name: 'Insert equation' });
  await expect(modal.getByRole('img')).toBeVisible();
  await modal.getByLabel('LaTeX source').fill(String.raw`\frac{1}{2} + \sqrt{x}`);
  await modal.getByLabel('Accessible description').fill('One half plus the square root of x');
  await expect(modal.getByRole('button', { name: 'Insert equation', exact: true })).toBeEnabled();
  await page.screenshot({ path: 'test-results/equation-editor.png', fullPage: true });
  const download = page.waitForEvent('download');
  await modal.getByRole('button', { name: 'Save SVG…' }).click();
  const svg = await readFile((await (await download).path())!, 'utf8');
  expect(svg).toContain('<path');
  await modal.getByRole('button', { name: 'Insert equation', exact: true }).click();
  const saved = await savedProject(page);
  const equation = saved.spreads[0].elements.find((element: { equation?: unknown }) => element.equation);
  expect(equation.equation.latex).toBe(String.raw`\frac{1}{2} + \sqrt{x}`);
  expect(equation.altText).toBe('One half plus the square root of x');
  await page.getByRole('button', { name: 'Edit equation…', exact: true }).click();
  await page.getByLabel('LaTeX source').fill(String.raw`\frac{`);
  await expect(page.getByRole('alert')).toBeVisible();
  await expect(page.getByRole('button', { name: 'Apply equation' })).toBeDisabled();
  await page.getByLabel('LaTeX source').fill('a^2 + b^2 = c^2');
  await expect(page.getByRole('button', { name: 'Apply equation' })).toBeEnabled();
  await page.getByRole('button', { name: 'Apply equation' }).click();
  await page.getByTitle('Undo (Ctrl+Z)', { exact: true }).click();
  const undone = await savedProject(page);
  expect(undone.spreads[0].elements.find((item: { id: string }) => item.id === equation.id).equation.latex).toBe(equation.equation.latex);
  await page.reload();
  await page.getByRole('button', { name: 'Edit equation…', exact: true }).click();
  await expect(page.getByLabel('LaTeX source')).toHaveValue(equation.equation.latex);
  await page.getByRole('button', { name: 'Cancel', exact: true }).click();
  await page.getByTitle('Canvas Zoom', { exact: true }).selectOption('fit');
  await page.screenshot({ path: 'test-results/equation-canvas.png', fullPage: true });
  const pdfDownload = page.waitForEvent('download');
  await page.getByTitle('Export Clean Digital PDF (Exact Trim Dimensions)').click();
  const pdfPath = (await (await pdfDownload).path())!;
  expect((await readFile(pdfPath)).subarray(0, 5).toString()).toBe('%PDF-');
  await mkdir('test-results/equations', { recursive: true });
  await copyFile(pdfPath, 'test-results/equations/equation.pdf');
  expect(errors).toEqual([]);
});
